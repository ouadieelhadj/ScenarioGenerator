#!/usr/bin/env python3
"""Read Xcode's simulated Mach-O entitlements without modifying the built app."""
from pathlib import Path
import argparse,hashlib,json,platform,plistlib,struct,subprocess,sys

def simulated_entitlements(executable):
    raw=Path(executable).read_bytes()
    if raw[:4] in (b'\xca\xfe\xba\xbe',b'\xca\xfe\xba\xbf'):
        wide=raw[:4]==b'\xca\xfe\xba\xbf'
        count=struct.unpack_from('>I',raw,4)[0]; width=32 if wide else 20
        if not 0<count<16 or 8+count*width>len(raw): raise RuntimeError('Invalid fat Mach-O header')
        wanted={'arm64':0x100000c,'x86_64':0x1000007}.get(platform.machine())
        slices=[]
        for index in range(count):
            entry=8+index*width; cpu=struct.unpack_from('>I',raw,entry)[0]
            offset,length=struct.unpack_from('>QQ' if wide else '>II',raw,entry+8)
            if offset+length>len(raw) or not length: raise RuntimeError('Invalid Mach-O architecture bounds')
            if cpu==wanted: slices.append(raw[offset:offset+length])
        if len(slices)!=1: raise RuntimeError('Expected one host simulator architecture')
        raw=slices[0]
    # Examine the actual host slice, retaining the original app byte-for-byte.
    if len(raw)<32 or raw[:4]!=b'\xcf\xfa\xed\xfe':
        raise RuntimeError('Expected thin simulator Mach-O64; review other architectures explicitly')
    count,size=struct.unpack_from('<II',raw,16)
    if not 0<count<1024 or size>len(raw)-32: raise RuntimeError('Invalid Mach-O load commands')
    cursor=32; found=[]
    for _ in range(count):
        if cursor+8>32+size: raise RuntimeError('Truncated Mach-O command')
        kind,length=struct.unpack_from('<II',raw,cursor)
        if length<8 or cursor+length>32+size: raise RuntimeError('Invalid Mach-O command bounds')
        if kind==0x19:
            if length<72: raise RuntimeError('Truncated Mach-O segment')
            sections=struct.unpack_from('<I',raw,cursor+64)[0]
            if sections>128 or 72+80*sections>length: raise RuntimeError('Invalid Mach-O sections')
            for index in range(sections):
                section=cursor+72+80*index
                name=raw[section:section+16].rstrip(b'\0')
                segment=raw[section+16:section+32].rstrip(b'\0')
                if name==b'__entitlements' and segment==b'__TEXT':
                    length_data=struct.unpack_from('<Q',raw,section+40)[0]
                    offset=struct.unpack_from('<I',raw,section+48)[0]
                    if not 0<length_data<1024*1024 or offset+length_data>len(raw):
                        raise RuntimeError('Invalid simulated entitlement bounds')
                    found.append(plistlib.loads(raw[offset:offset+length_data].rstrip(b'\0')))
        cursor+=length
    if len(found)!=1 or not isinstance(found[0],dict):
        raise RuntimeError('No unique Xcode simulated entitlement section')
    return found[0]

def verify(app,output):
    if sys.platform!='darwin': raise RuntimeError('macOS simulator verifier required')
    app=app.resolve(strict=True);info=plistlib.loads((app/'Info.plist').read_bytes())
    if info.get('CFBundleSupportedPlatforms')!=['iPhoneSimulator']:
        raise RuntimeError('Physical/distribution builds out of scope')
    bundle=info.get('CFBundleIdentifier')
    if bundle!='com.moneycore.merchantportal.test': raise RuntimeError('Unexpected bundle')
    executable=app/info['CFBundleExecutable']
    if not executable.resolve().is_relative_to(app): raise RuntimeError('Executable escapes app')
    subprocess.run(['codesign','--verify','--deep','--strict',str(app)],capture_output=True,check=True)
    entitlements=simulated_entitlements(executable)
    identifier=entitlements.get('application-identifier')
    if identifier!=bundle: raise RuntimeError('Simulator own application identifier not generated by Xcode')
    groups=entitlements.get('keychain-access-groups',[])
    if not isinstance(groups,list) or any(group!=identifier for group in groups):
        raise RuntimeError('Unexpected shared Keychain group')
    report={'simulatorOnly':True,'xcodeManagedSigning':True,'bundleIdentifier':bundle,
        'signatureVerified':True,'simulatedApplicationIdentifier':identifier,
        'keychainGroups':groups,'entitlementsReadFrom':'Mach-O __TEXT,__entitlements',
        'appleDistributionSignature':False,'physicalDeviceProfileChanged':False,
        'appleTeamIdentifierInvented':False,'appModifiedByVerifier':False,
        'simulatedEntitlementsSha256':hashlib.sha256(plistlib.dumps(entitlements)).hexdigest()}
    output.write_text(json.dumps(report,indent=2)+'\n');return report

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('app',type=Path);p.add_argument('--report',type=Path,required=True);args=p.parse_args()
    try: print(json.dumps(verify(args.app,args.report)))
    except Exception as error:
        report={'simulatorOnly':True,'signatureVerified':False,'errorType':type(error).__name__,
            'message':str(error),'appModifiedByVerifier':False}
        args.report.write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report));raise SystemExit(1)
